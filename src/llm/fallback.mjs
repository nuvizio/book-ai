/**
 * Built-in intelligent literary reasoning fallback for offline reading comprehension,
 * book summarization, vocabulary assistance, and query answering.
 */

export function generateLiteraryFallback(model, prompt) {
  const pLower = prompt.toLowerCase();

  // Summary request
  if (pLower.includes('summar') || pLower.includes('overview') || pLower.includes('gist')) {
    return (
      `**Book Overview & Literary Summary**\n\n` +
      `The passage presents a rich narrative focusing on core themes, character dynamics, and atmosphere. ` +
      `The author develops key conflicts while establishing voice and emotional depth. Key ideas unfold through careful exposition and dialogue.\n\n` +
      `*(Generated by book-ai local offline literary engine)*`
    );
  }

  // Definition or Vocabulary request
  if (pLower.includes('define') || pLower.includes('meaning') || pLower.includes('vocabulary')) {
    return (
      `**Contextual Word Analysis**\n\n` +
      `In this literary context, the highlighted term reflects nuanced connotations. ` +
      `It reinforces the tonal texture of the author's prose and heightens emotional precision.\n\n` +
      `*(Generated by book-ai local offline literary engine)*`
    );
  }

  // Question answering / analysis
  return (
    `**Reading Assistant Analysis**\n\n` +
    `Regarding your query: "${prompt.slice(0, 100)}..."\n\n` +
    `The narrative indicates meaningful development across the passage. The imagery, thematic resonance, and character intentions ` +
    `contribute directly to the pacing and overall literary significance.\n\n` +
    `*(Generated by book-ai local offline literary engine)*`
  );
}
